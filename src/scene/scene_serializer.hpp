#ifndef SCENE_SERIALIZER_HPP
#define SCENE_SERIALIZER_HPP

#include "scene.hpp"
#include <fstream>
#include <iomanip>
#include <sstream>
#include <unordered_map>
#include <vector>

// Minimal JSON-like scene format serializer
// Format: Human-readable text format for scene data

class SceneSerializer {
public:
  static bool SaveToFile(Scene &scene, const std::string &filepath) {
    std::ofstream file(filepath);
    if (!file.is_open()) {
      std::cerr << "[SceneSerializer] Failed to open file for writing: "
                << filepath << std::endl;
      return false;
    }

    file << "# Scene File Format v1.1\n";
    file << "# Auto-generated by OpenGL Engine\n\n";

    file << "scene {\n";

    auto &reg = scene.GetRegistry();

    // Assign stable ids by iteration order so parent refs survive save/load
    std::unordered_map<entt::entity, int> stableIds;
    int nextId = 0;
    auto &entityPool = reg.storage<entt::entity>();
    for (auto entityID : entityPool) {
      stableIds[entityID] = nextId++;
    }

    size_t entityCount = 0;
    for (auto entityID : entityPool) {
      Entity entity{entityID, &scene};
      WriteEntity(file, entity, stableIds, 1);
      entityCount++;
    }

    file << "}\n";

    std::cout << "[SceneSerializer] Saved scene with " << entityCount
              << " entities to: " << filepath << std::endl;
    return true;
  }

  static bool LoadFromFile(Scene &scene, const std::string &filepath) {
    std::ifstream file(filepath);
    if (!file.is_open()) {
      std::cerr << "[SceneSerializer] Failed to open file for reading: "
                << filepath << std::endl;
      return false;
    }

    scene.Clear();

    struct PendingEntity {
      std::string name = "Entity";
      int id = -1;
      int parentId = -1;
      TransformComponent transform;
    };

    std::vector<PendingEntity> pending;
    PendingEntity current;
    bool inEntity = false;
    bool inTransform = false;

    std::string line;
    while (std::getline(file, line)) {
      line = Trim(line);

      if (line.empty() || line[0] == '#')
        continue;

      if (line.find("entity") == 0 && line.find("{") != std::string::npos) {
        size_t start = line.find('"');
        size_t end = line.rfind('"');
        current = PendingEntity{};
        if (start != std::string::npos && end != std::string::npos &&
            end > start) {
          current.name = line.substr(start + 1, end - start - 1);
        }
        inEntity = true;
        inTransform = false;
      } else if (inEntity && line == "transform {") {
        inTransform = true;
      } else if (inTransform && line == "}") {
        inTransform = false;
      } else if (inEntity && !inTransform && line == "}") {
        pending.push_back(current);
        inEntity = false;
      } else if (inTransform) {
        ParseTransformLine(line, current.transform);
      } else if (inEntity) {
        std::istringstream iss(line);
        std::string key;
        iss >> key;
        if (key == "id") {
          iss >> current.id;
        } else if (key == "parent") {
          iss >> current.parentId;
        }
      }
    }

    // Pass 1: create all entities, record stableId -> handle
    std::unordered_map<int, entt::entity> idMap;
    std::vector<entt::entity> createdHandles;
    createdHandles.reserve(pending.size());
    for (auto &p : pending) {
      auto entity = scene.CreateEntity(p.name);
      auto &tc = entity.GetTransform();
      tc.Position = p.transform.Position;
      tc.Rotation = p.transform.Rotation;
      tc.Scale = p.transform.Scale;
      auto handle = (entt::entity)entity;
      createdHandles.push_back(handle);
      if (p.id >= 0)
        idMap[p.id] = handle;
    }

    // Pass 2: wire parent/children from stable ids
    auto &reg = scene.GetRegistry();
    for (size_t i = 0; i < pending.size(); ++i) {
      const auto &p = pending[i];
      if (p.parentId < 0)
        continue;
      auto pIt = idMap.find(p.parentId);
      if (pIt == idMap.end())
        continue;
      entt::entity childHandle = createdHandles[i];
      entt::entity parentHandle = pIt->second;
      if (childHandle == parentHandle)
        continue;
      auto &childTc = reg.get<TransformComponent>(childHandle);
      auto &parentTc = reg.get<TransformComponent>(parentHandle);
      childTc.Parent = parentHandle;
      parentTc.Children.push_back(childHandle);
    }

    std::cout << "[SceneSerializer] Loaded scene with "
              << scene.GetEntityCount() << " entities from: " << filepath
              << std::endl;
    return true;
  }

private:
  static void WriteEntity(std::ostream &out, Entity entity,
                          const std::unordered_map<entt::entity, int> &ids,
                          int indent) {
    std::string tab(indent * 2, ' ');

    out << tab << "entity \"" << entity.GetName() << "\" {\n";

    auto handle = (entt::entity)entity;
    auto it = ids.find(handle);
    int id = (it != ids.end()) ? it->second : -1;
    out << tab << "  id " << id << "\n";

    const auto &tc = entity.GetTransform();
    int parentId = -1;
    if (tc.Parent != entt::null) {
      auto pIt = ids.find(tc.Parent);
      if (pIt != ids.end())
        parentId = pIt->second;
    }
    if (parentId >= 0)
      out << tab << "  parent " << parentId << "\n";

    WriteTransform(out, tc, indent + 1);

    out << tab << "}\n";
  }

  static void WriteTransform(std::ostream &out, const TransformComponent &t,
                             int indent) {
    std::string tab(indent * 2, ' ');

    out << tab << "transform {\n";
    out << tab << "  position " << t.Position.x << " " << t.Position.y << " "
        << t.Position.z << "\n";
    out << tab << "  rotation " << t.Rotation.x << " " << t.Rotation.y << " "
        << t.Rotation.z << "\n";
    out << tab << "  scale " << t.Scale.x << " " << t.Scale.y << " "
        << t.Scale.z << "\n";
    out << tab << "}\n";
  }

  static void ParseTransformLine(const std::string &line,
                                 TransformComponent &t) {
    std::istringstream iss(line);
    std::string key;
    iss >> key;

    if (key == "position") {
      iss >> t.Position.x >> t.Position.y >> t.Position.z;
    } else if (key == "rotation") {
      iss >> t.Rotation.x >> t.Rotation.y >> t.Rotation.z;
    } else if (key == "scale") {
      iss >> t.Scale.x >> t.Scale.y >> t.Scale.z;
    }
  }

  static std::string Trim(const std::string &str) {
    size_t first = str.find_first_not_of(" \t\r\n");
    if (first == std::string::npos)
      return "";
    size_t last = str.find_last_not_of(" \t\r\n");
    return str.substr(first, last - first + 1);
  }
};

#endif // SCENE_SERIALIZER_HPP
